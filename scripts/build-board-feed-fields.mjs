#!/usr/bin/env node
// Generates base44/shared/boardFeedFields.ts — the server-side projection
// allowlist used by boardFeed. Rebuild after changing an entity schema or
// FEEDABLE's heavy list:
//
//   node scripts/build-board-feed-fields.mjs          # write
//   node scripts/build-board-feed-fields.mjs --check  # verify only
//
// The allowlist must cover every field stored documents can carry, or rows
// come back silently missing data. Fields below are schema fields + system
// fields + KNOWN_EXTRAS (verified against live rows — e.g. _salesTaskAdoption
// exists in stored WorkOrder docs but is not declared in the schema).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Mirrors FEEDABLE in base44/functions/boardFeed/entry.ts — keep in sync.
const FEEDABLE = {
  WorkOrder: ["smartsheet_sync_snapshot", "work_notes", "sales_import_snapshot", "smartsheet_create_attempt"],
  Order: ["smartsheet_sync_snapshot", "work_notes", "smartsheet_create_attempt"],
};

// Undeclared fields observed in stored documents (verified via live feed
// pulls). Add entries here if a stored-doc-only field ever appears.
const KNOWN_EXTRAS = {
  WorkOrder: ["_salesTaskAdoption"],
};

const SYSTEM_FIELDS = ["id", "created_date", "updated_date", "created_by", "created_by_id", "is_sample"];

function readJsonc(path) {
  const raw = readFileSync(path, "utf8");
  const clean = raw
    .replace(/^\s*\/\/.*$/gm, "")
    .replace(/\/\/.*$/gm, "")
    .replace(/,(\s*[}\]])/g, "$1");
  return JSON.parse(clean);
}

const out = {};
for (const [entity, heavy] of Object.entries(FEEDABLE)) {
  const schema = readJsonc(join(root, "base44", "entities", `${entity}.jsonc`));
  const props = Object.keys(schema?.properties || {});
  if (!props.length) throw new Error(`${entity}: no schema properties found`);
  const fields = [...new Set([...SYSTEM_FIELDS, ...props, ...(KNOWN_EXTRAS[entity] || [])])]
    .filter((f) => !heavy.includes(f))
    .sort();
  for (const h of heavy) {
    if (fields.includes(h)) throw new Error(`${entity}: heavy field '${h}' leaked into projection`);
  }
  out[entity] = fields;
}

const ts = `// GENERATED by scripts/build-board-feed-fields.mjs — do not edit by hand.
// Re-run the generator after changing an entity schema or FEEDABLE's heavy
// list, then redeploy boardFeed. Server-side projection keeps the heavy sync
// blobs (~85% of WorkOrder row bytes) out of entity reads entirely instead of
// fetching them and stripping them afterward.
export const FEED_FIELDS: Record<string, string[]> = ${JSON.stringify(out, null, 2)};
`;

const target = join(root, "base44", "shared", "boardFeedFields.ts");
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current === ts) {
    console.log("boardFeedFields.ts matches schemas and heavy lists.");
  } else {
    console.error("boardFeedFields.ts is stale — run scripts/build-board-feed-fields.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, ts);
  for (const [entity, fields] of Object.entries(out)) {
    console.log(`${entity}: ${fields.length} fields projected`);
  }
  console.log(`wrote ${target}`);
}
