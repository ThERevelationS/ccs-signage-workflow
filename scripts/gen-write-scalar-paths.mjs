#!/usr/bin/env node
// Generates base44/shared/entityScalarWritePaths.ts — a per-entity map of
// declared SCALAR field paths (string/number/integer/boolean), including paths
// nested inside array items ("notes.items.assigned_to"). staffEntityWrite uses
// it to coerce the known offender shape: an array written into a scalar field
// (e.g. assigned_to: ["name"] inside WorkOrder.notes[]).
// Re-run whenever entities change: node scripts/gen-write-scalar-paths.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const SCALARS = new Set(['string', 'number', 'integer', 'boolean']);
const out = {};
for (const f of readdirSync('base44/entities').sort()) {
  if (!f.endsWith('.jsonc')) continue;
  let j;
  try { j = JSON.parse(readFileSync(`base44/entities/${f}`, 'utf8')); } catch { continue; }
  const name = j.name || f.replace(/\.jsonc$/, '');
  const paths = {};
  const walk = (props, prefix, depth) => {
    if (!props || typeof props !== 'object' || depth > 6) return;
    for (const [field, spec] of Object.entries(props)) {
      if (!spec || typeof spec !== 'object') continue;
      const p = prefix ? `${prefix}.${field}` : field;
      if (SCALARS.has(spec.type)) paths[p] = spec.type;
      else if (spec.type === 'array' && spec.items?.properties) walk(spec.items.properties, `${p}.items`, depth + 1);
      else if (spec.type === 'object' && spec.properties) walk(spec.properties, p, depth + 1);
    }
  };
  walk(j.properties, '', 0);
  if (Object.keys(paths).length) out[name] = paths;
}

const ts = `// GENERATED by scripts/gen-write-scalar-paths.mjs — do not hand-edit.
// Declared scalar field paths per entity, incl. paths inside array items.
export const ENTITY_SCALAR_WRITE_PATHS: Record<string, Record<string, 'string' | 'number' | 'integer' | 'boolean'>> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync('base44/shared/entityScalarWritePaths.ts', ts);
console.log(`entities: ${Object.keys(out).length} | total scalar paths: ${Object.values(out).reduce((n, m) => n + Object.keys(m).length, 0)}`);
