import {build} from 'esbuild';
import fs from 'node:fs/promises';
const source='base44/functions/findLocalityByAddress/handler.ts';
const targets=['base44/functions/findLocalityByAddress/entry.ts','base44/functions/resolvePermittingAddress/entry.ts'];
const r=await build({entryPoints:[source],bundle:true,format:'esm',platform:'neutral',target:'es2022',external:['npm:*','node:*'],write:false});
const code='// Generated by scripts/build-permitting-address-runtime.mjs; edit findLocalityByAddress/handler.ts, then regenerate.\n'+r.outputFiles[0].text;
for(const target of targets){
 if(process.argv.includes('--check')){
  if((await fs.readFile(target,'utf8')).trimEnd()!==code.trimEnd())throw Error('Address runtime is stale: '+target);
 }else await fs.writeFile(target,code);
}
console.log(process.argv.includes('--check')?'Both address runtimes match canonical source and shared dependencies.':'Regenerated both standalone address runtimes; activate each using Base44 write_file.');