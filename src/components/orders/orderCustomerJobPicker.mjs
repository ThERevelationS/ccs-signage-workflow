// Order Form customer picker only. A won job may still be in production;
// exclude terminal job states, not every closed sales opportunity.
const TERMINAL = new Set(["lost", "completed", "closed"]);
const normalized = (value) => String(value ?? "").trim().toLowerCase();
const LEGACY_CLOSED_TASK = /^(lost\b|completed sale\b|closed\b)/i;

export function isActiveOrderCustomerJob(job) {
  if (!job?.id || job.deleted === true || job.completed === true || job.is_rider === true || job.closed === true) return false;
  // Historical imports may have sales_status='lead' and in_pipeline=true
  // even when their current task explicitly says Completed Sale, Lost, or Closed.
  // Treat that terminal evidence consistently for modern and legacy records.
  if (LEGACY_CLOSED_TASK.test(String(job.current_task_description ?? "").trim())) return false;
  return !TERMINAL.has(normalized(job.current_stage)) &&
    !TERMINAL.has(normalized(job.sales_status)) &&
    !TERMINAL.has(normalized(job.status));
}

// Some Sales-synced WorkOrders have an autogenerated placeholder in title,
// which is metadata rather than a project description. Never render it in
// the Order Form customer picker or use it as a search term.
export function cleanOrderJobTitle(value) {
  const title = String(value ?? "").trim();
  return /^(?:imported from\s+)?smartsheet row\s*#?\s*\d+$/i.test(title) ? "" : title;
}

export function orderCustomerJobSubtitle(job) {
  return cleanOrderJobTitle(job?.description) || cleanOrderJobTitle(job?.title) ||
    (String(job?.current_task_description ?? "").trim()
      ? `Current task: ${String(job.current_task_description).trim()}` : "No project title");
}

export function filterOrderCustomerJobs(jobs, searchTerm, limit = 10) {
  const terms = normalized(searchTerm).split(/\s+/).filter(Boolean);
  return (Array.isArray(jobs) ? jobs : [])
    .filter(isActiveOrderCustomerJob)
    .filter(job => {
      if (!terms.length) return true;
      const searchable = [job.client_name, cleanOrderJobTitle(job.title), cleanOrderJobTitle(job.description)]
        .filter(Boolean).join(" ").toLowerCase();
      return terms.every(term => searchable.includes(term));
    })
    .slice(0, limit);
}
