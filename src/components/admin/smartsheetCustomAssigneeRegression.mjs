import assert from "node:assert/strict";
import { reviewedCustomAssigneeNames, resolveSmartsheetTaskAssignee } from "./smartsheetTaskAssigneeModel.js";
import { buildSmartsheetVocabularyReview, smartsheetVocabularyReadyForBinding } from "./smartsheetVocabularyReviewModel.js";
import { buildSmartsheetControlledCreationProposals } from "./smartsheetControlledCreationProposalModel.js";
import { buildSmartsheetDryRunPreview } from "./smartsheetDryRunModel.js";
import { validateCustomAssigneeName } from "../sales/customAssigneeName.js";

const user = (full_name) => ({ full_name, sales_roles: ["Task Assigned"], is_active: true });
const users = [user("Brett Heinlein")];
const customSetting = { setting_value: { items: [{ kind: "custom_name", label: "Emily", sheet_id: "sales", column_id: "owner", confirmed_at: "2026-09-23T18:00:00Z" }] } };
const names = reviewedCustomAssigneeNames(customSetting.setting_value, "sales", "owner");
assert.deepEqual(names, ["Emily"]);
assert.deepEqual(reviewedCustomAssigneeNames(customSetting.setting_value, "other", "owner"), []);
assert.deepEqual(reviewedCustomAssigneeNames(customSetting.setting_value, "sales", "other"), []);
assert.equal(resolveSmartsheetTaskAssignee("Emily", users).state, "unresolved");
const custom = resolveSmartsheetTaskAssignee("Emily", users, names);
assert.equal(custom.state, "confirmed_custom_name");
assert.equal(custom.name, "Emily");
assert.equal(custom.user, null);
assert.equal(resolveSmartsheetTaskAssignee("EMILY", users, names).state, "unresolved");
assert.equal(resolveSmartsheetTaskAssignee("Brett", users, names).name, "Brett Heinlein");
assert.equal(resolveSmartsheetTaskAssignee("Brett", [...users, user("Brett Other")], ["Brett"]).state, "ambiguous");
assert.equal(resolveSmartsheetTaskAssignee("Emily", [user("Emily")], names).custom, false);
assert.equal(resolveSmartsheetTaskAssignee("Brett", [{ ...users[0], is_active: false }]).state, "unresolved");
assert.equal(validateCustomAssigneeName("  Cameron  "), "Cameron");
assert.throws(() => validateCustomAssigneeName("   "));
assert.throws(() => validateCustomAssigneeName("one\ntwo"));
assert.throws(() => validateCustomAssigneeName("x".repeat(101)));
const column = (field, options, id = field) => ({ field, status: "matched", matches: [{ id, type: "PICKLIST", options }] });
const analysis = { sales: { status: "ready", sheet: { id: "sales" }, analysis: { fields: [column("lead_source", ["Web"]), column("current_task_description", ["SIPs"]), column("current_task_assigned_to", ["Brett", "Emily"], "owner")] } }, orders: { status: "ready", analysis: { fields: [column("request_type", ["Substrate", "Vinyl", "Supplies", "Other"])] } } };
const args = { liveMappingAnalysis: analysis, leadSources: ["Website"], taskDescriptions: ["SIPs"], authorizedUsers: users };
assert.equal(smartsheetVocabularyReadyForBinding(buildSmartsheetVocabularyReview(args)), false);
const review = buildSmartsheetVocabularyReview({ ...args, customAssigneeSetting: customSetting });
assert.deepEqual(review.owners.confirmedCustom, ["Emily"]);
assert.equal(smartsheetVocabularyReadyForBinding(review), true);
assert.equal(smartsheetVocabularyReadyForBinding(buildSmartsheetVocabularyReview({ ...args, customAssigneeSetting: customSetting, authorizedUsers: [...users, user("Matias")] })), false);
const blueprint = [{ field: "current_task_assigned_to", label: "Task assigned", direction: "both" }];
const columnBindings = { current_task_assigned_to: { column_id: "owner" } };
const source = { row_id: "row", status: "new_record", values: { client_name: "Customer", current_task_assigned_to: "Emily" } };
const proposalArgs = { rows: [source], creationReadiness: { state: "ready", rows: [{ row_id: "row", blockers: [], ready_for_controlled_create_review: true, customer: { ready: true, state: "exact_existing", customer_id: "customer" } }] }, dataset: "sales", sheetId: "sales", customers: [{ id: "customer", company_name: "Customer" }], blueprint, columnBindings, authorizedUsers: users };
const before = JSON.stringify(proposalArgs);
const unapproved = buildSmartsheetControlledCreationProposals(proposalArgs);
assert.ok(unapproved.rows[0].blockers.some((item) => item.code === "task_owner_translation_required"));
const approved = buildSmartsheetControlledCreationProposals({ ...proposalArgs, customAssigneeNames: names });
assert.equal(approved.rows[0].proposed_payload.current_task_assigned_to, "Emily");
assert.equal(approved.rows[0].fields[0].state, "confirmed_custom_name");
assert.equal(approved.creation_enabled, false);
assert.equal(approved.automatic_creates, 0);
assert.equal(JSON.stringify(proposalArgs), before);
const dryRun = buildSmartsheetDryRunPreview({ sheetId: "sales", dataset: "sales", blueprint, columnBindings, authorizedUsers: users, customAssigneeNames: names, smartsheetRows: [{ id: "row", cells: [{ column_id: "owner", value: "Emily" }] }], base44Rows: [{ id: "wo", smartsheet_sheet_id: "sales", smartsheet_row_id: "row", current_task_assigned_to: "Emily" }] });
assert.equal(dryRun.rows[0].status, "linked_same");
console.log("Smartsheet custom-assignee regression: PASS");